// ===== 续写消息模板 =====
export function buildFirstChapterUserMessage(novelText: string, creativeIdea: string): string {
  const idea = creativeIdea.trim() || AUTO_CREATIVE_IDEA
  return `# 原作小说
${novelText}

---

# 用户的最新创意/要求
${idea}

---

请根据以上所有材料，创作同人小说的第 1 章。

**输出格式硬性要求**：
- 第一行必须严格遵循 \`# 第N章 章节标题\` 格式（markdown 一级标题 + 章节序号 + 空格 + 标题文本）
- 例：\`# 第一章 风起于青萍之末\`
- 标题之后空一行开始正文，全文使用 markdown 段落格式
- 不要输出任何说明、注释、元信息或代码块包裹`
}

export function buildNextChapterUserMessage(num: number, creativeIdea: string): string {
  const idea = creativeIdea.trim() || AUTO_CREATIVE_IDEA
  return `继续创作下一章（第 ${num} 章）。

创作方向：${idea}

**输出格式硬性要求**：第一行必须为 \`# 第${num}章 章节标题\`（markdown 一级标题），标题后空一行开始正文。不要输出任何说明、注释或代码块。`
}

